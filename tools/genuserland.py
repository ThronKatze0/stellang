#!/usr/bin/env python3
"""Embed StellaOS's userland sources (examples/stellaos/userland/*.st: the runtime that compiled
programs carry, and the example programs a fresh disk starts with) into
examples/stellaos/userland.st, so the kernel has them without a file system to read them from.

    python3 tools/genuserland.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "examples/stellaos/userland"
out = root / "examples/stellaos/userland.st"


def lit(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${").replace("\t", "\\t") + '"'


def lines(text):
    return "[\n" + "".join(f"        {lit(l)},\n" for l in text.split("\n")) + "    ]"


parts = [
    "// Generated by tools/genuserland.py from examples/stellaos/userland/: don't edit, edit those.",
    "",
    "// the runtime compiled along with every program (userland/crt.st)",
    "fn runtime() -> str {",
    f"    let ls = {lines((src / 'crt.st').read_text())}",
    '    return ls.join("\\n")',
    "}",
    "",
    "// the example programs: [file name, source]",
    "fn programs() -> [[str]] {",
    "    var all: [[str]] = []",
]
for f in sorted(src.glob("*.st")):
    if f.name == "crt.st":
        continue
    parts.append(f"    all.push([{lit(f.name)}, {lines(f.read_text())}.join(\"\\n\")])")
parts += ["    return all", "}", ""]
out.write_text("\n".join(parts))
print(f"wrote {out.relative_to(root)}")
