#!/usr/bin/env python3
# Renders the fonts StellaOS draws text with into src/runtime_font.c: anti-aliased glyph bitmaps
# (one byte of coverage per pixel) for a few faces and sizes.
#
#     python3 tools/genfont.py > src/runtime_font.c
#
# Needs Pillow and the Inter and DejaVu fonts (Debian/Ubuntu: fonts-inter fonts-dejavu-core).
# Inter: SIL Open Font License 1.1, (c) The Inter Project Authors. DejaVu: Bitstream Vera license
# with DejaVu changes in the public domain. Both allow embedding the rendered glyphs.

import sys
from PIL import ImageFont

INTER = "/usr/share/fonts/opentype/inter/Inter-{}.otf"
DEJAVU = "/usr/share/fonts/truetype/dejavu/DejaVuSans{}.ttf"

# (name, file, pixel size). The index is the face number stellang code uses (std/gfx.st).
FACES = [
    ("ui", INTER.format("Regular"), 13),
    ("ui_bold", INTER.format("SemiBold"), 13),
    ("text", INTER.format("Regular"), 16),
    ("text_bold", INTER.format("SemiBold"), 16),
    ("title", INTER.format("Bold"), 22),
    ("mono", DEJAVU.format("Mono"), 13),
    ("mono_bold", DEJAVU.format("Mono-Bold"), 13),
    ("big", INTER.format("Bold"), 34),
]

# Latin-1 plus a few symbols that UIs and games like
EXTRA = "✦★☆•…–—‘’“”€←↑→↓↵✓✔✕✖●○■□▲▶▼◀♥♦♣♠⌫☰▤≡✹⚑✎◉⚙♪⌂✉☺◎↻🔒"
# Latin (with Extended-A: most European languages), Greek and Cyrillic, and the symbols above
CODES = list(range(32, 127)) + list(range(160, 0x180)) + list(range(0x391, 0x3ca)) + [0x401] + list(range(0x410, 0x450)) + [0x451] + sorted(ord(c) for c in EXTRA)
FALLBACK = DEJAVU.format("")


def render(path, size):
    font = ImageFont.truetype(path, size)
    fallback = ImageFont.truetype(FALLBACK, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for cp in CODES:
        ch = chr(cp)
        f = font
        # a glyph the font doesn't have comes out as the .notdef box: use DejaVu for it
        if cp > 255 and font.getmask(ch).getbbox() == font.getmask("￿").getbbox():
            f = fallback
        adv = round(f.getlength(ch))
        mask, (ox, oy) = f.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        bbox = mask.getbbox()
        if not bbox or ch == " ":
            glyphs.append((cp, adv, 0, 0, 0, 0, 0))
            continue
        x0, y0, x1, y1 = bbox
        off = len(data)
        for y in range(y0, y1):
            for x in range(x0, x1):
                data.append(mask.getpixel((x, y)))
        glyphs.append((cp, adv, ox + x0, oy + y0, x1 - x0, y1 - y0, off))
    return ascent, descent, glyphs, data


def main():
    out = sys.stdout
    out.write("// Generated by tools/genfont.py: anti-aliased glyphs for the kernel's text drawing\n")
    out.write("// (runtime_kernel.c). Rendered from Inter (SIL Open Font License 1.1, (c) The Inter Project\n")
    out.write("// Authors) and DejaVu Sans / Sans Mono (Bitstream Vera license). Do not edit.\n\n")
    out.write("typedef struct { uint32_t cp; int16_t adv, x, y; uint8_t w, h; uint32_t off; } Glyph;\n")
    out.write("typedef struct { int ascent, descent, n; const Glyph *g; const uint8_t *a; } Face;\n\n")
    names = []
    for name, path, size in FACES:
        ascent, descent, glyphs, data = render(path, size)
        out.write(f"static const uint8_t font_{name}_a[{max(len(data), 1)}] = {{")
        for i, b in enumerate(data):
            if i % 32 == 0:
                out.write("\n")
            out.write(f"{b},")
        out.write("\n};\n")
        out.write(f"static const Glyph font_{name}_g[{len(glyphs)}] = {{\n")
        for g in glyphs:
            out.write("{%d,%d,%d,%d,%d,%d,%d},\n" % g)
        out.write("};\n\n")
        names.append((name, ascent, descent, len(glyphs)))
    out.write(f"#define NFACES {len(names)}\n")
    out.write("static const Face faces[NFACES] = {\n")
    for name, ascent, descent, n in names:
        out.write(f"    {{{ascent}, {descent}, {n}, font_{name}_g, font_{name}_a}},\n")
    out.write("};\n")


main()
