#!/usr/bin/env python3
# Make examples/stellaos/roots.st, StellaOS's trusted root certificates, from Mozilla's list as
# curl publishes it:
#
#     curl -o cacert.pem https://curl.se/ca/cacert.pem
#     python3 tools/genroots.py cacert.pem > examples/stellaos/roots.st
import base64, re, sys
text = open(sys.argv[1]).read()
date = re.search(r"Certificate data from Mozilla as of: (.*)", text)
# each entry: its name, a line of =, comment lines (# ...), then the certificate
blocks = re.findall(r"\n([^\n#=][^\n]*)\n=+\n(?:#[^\n]*\n)*-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----", text, re.S)
print("// The root certificates StellaOS trusts for HTTPS: Mozilla's list (the one Firefox uses),")
print("// %s, from https://curl.se/ca/cacert.pem." % ("as of " + date.group(1) if date else "unknown date"))
print("// Generated by tools/genroots.py; more can be added at run time as PEM files in /etc/ca.")
print("")
print("const ROOTS = [")
for name, b64 in blocks:
    der = base64.b64decode("".join(b64.split()))
    print("    // %s" % name.strip())
    print('    "%s",' % der.hex())
print("]")
